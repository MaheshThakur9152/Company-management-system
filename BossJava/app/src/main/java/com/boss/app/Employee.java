package com.boss.app;

public class Employee {
    public String id;
    public String name;
    public String site;
    public String role;
    public String avatarInitials;

    public Employee(String id, String name, String site, String role, String avatarInitials) {
        this.id = id;
        this.name = name;
        this.site = site;
        this.role = role;
        this.avatarInitials = avatarInitials;
    }
}
